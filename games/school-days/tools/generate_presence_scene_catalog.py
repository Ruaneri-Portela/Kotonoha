"""Build a privacy-oriented visual metadata allowlist from authenticated HQ.

Only numeric fingerprints are emitted. No media, text or retail script data
is copied into the repository. An unknown or changed script fails closed.
The catalog is a conservative metadata classification, not a visual audit.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re

from build_lxh_locale_gpks import GpkReader
from normalize_spanish_script_gpk import NativeOrs, read_ktrf_scenes

SCRIPT_SHA = "e82dc824449381b9a132aa092740c4169eb3d77a820d969046b74ca1d9df4adf"
ROUTE_SHA = "557830833aa3bb4a8efba82fe75964211491e9f02d60d6090dda1d5174d4e745"
VISUAL = {"CreateBG": (b"b", 2), "PlayMovie": (b"m", 1), "EndRoll": (b"e", 1)}


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def normalize(value: bytes) -> bytes:
    return value.lower().replace(b"\\", b"/")


def media_private(path: bytes) -> bool:
    return any(re.match(rb"h[0-9][-_]", part)
               for part in normalize(path).split(b"/"))


def opening(key: str, paths: list[bytes]) -> bool:
    return bool(re.search(r"-op[0-9]*$", key)) or any(
        re.search(rb"(?:^|/)(?:sdhq[_-]|sdv0[123](?:[./_-]|$))", normalize(p))
        for p in paths
    )


def family(key: str) -> str:
    return re.sub(r"[0-9]{2}$", "", key)


def visual_events(data: bytes):
    for event in NativeOrs(data).events:
        if event.kind in VISUAL:
            tag, index = VISUAL[event.kind]
            yield tag, event.fields[index], event.start, event.end


def fingerprint(key: str, events) -> int:
    value = 14695981039346656037
    chunks = [normalize(key.encode("ascii")) + b"\0"]
    for tag, path, start, end in events:
        chunks += [tag, normalize(path) + b"\0", start.to_bytes(8, "little"),
                   end.to_bytes(8, "little")]
    for chunk in chunks:
        for byte in chunk:
            value = ((value ^ byte) * 1099511628211) & ((1 << 64) - 1)
    return value


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--script", type=Path, required=True)
    parser.add_argument("--route", type=Path, required=True)
    parser.add_argument("--oracle", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if digest(args.script) != SCRIPT_SHA or digest(args.route) != ROUTE_SHA:
        raise SystemExit("Unrecognized retail script or route SHA-256")
    pack = GpkReader(args.script)
    keys = read_ktrf_scenes(args.route)
    oracle = {key.lower() for key in re.findall(
        r'"(0[0-5]/0[0-5]-[A-Z0-9]+-[A-Z0-9]+)"',
        args.oracle.read_text(encoding="utf-8"))}
    if len(oracle) != 122:
        raise SystemExit("Replay oracle inventory changed")
    scripts = {}
    marked = set()
    for path in pack.entries:
        if not re.fullmatch(r"english/0[0-5]/[^/]+\.eng\.ors", path):
            continue
        key = path.removeprefix("english/").removesuffix(".eng.ors")
        events = list(visual_events(pack.read_ors(path)))
        scripts[path] = (key, events)
        if any(media_private(event[1]) for event in events):
            marked.add(key)
    # Suppress all siblings of every observed replay/marked scene as well.
    private_families = {family(key) for key in oracle | marked}
    allowed = []
    counts = [0] * 6
    for path in keys:
        key, events = scripts[path]
        if (not events or family(key) in private_families
                or opening(key, [event[1] for event in events])):
            continue
        allowed.append(fingerprint(key, events))
        counts[int(key[:2])] += 1
    if len(allowed) != len(set(allowed)):
        raise SystemExit("Duplicate scene fingerprints")
    lines = ["// Generated by generate_presence_scene_catalog.py.",
             "// Authenticated HQ v1.02; conservative visual metadata only.",
             "// No retail media, script text or asset paths are embedded.",
             "static constexpr std::uint64_t kPublicVisualSignatures[] = {"]
    for value in sorted(allowed):
        lines.append(f"    UINT64_C(0x{value:016x}),")
    lines.append("};")
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Route scenes: {len(keys)}; Replay: {len(oracle)}; media marked: "
          f"{len(marked)}; union: {len(oracle | marked)}; "
          f"private families: {len(private_families)}; "
          f"allowlisted: {len(allowed)} {counts}; "
          f"fallback: {len(keys)-len(allowed)}")


if __name__ == "__main__":
    main()
